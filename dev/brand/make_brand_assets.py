#!/usr/bin/env python3
"""ITC NetCore product brand assets derived from the approved L1 vector artwork (development tooling only).

Every raster is rendered from the byte-identical v0.7 SVGs in ui/ui/images/brand/ (ASSETS.txt) with rsvg-convert, then
composed with Pillow onto a plain tile. Nothing is redrawn or regenerated by AI; the mark keeps its geometry and colours.
    python3 dev/brand/make_brand_assets.py            (from the repository root)
Outputs (same names as the assets they replace, so no code path changes):
  ui/ui/images/pwa/icon-180.png, icon-192.png, icon-512.png, icon-maskable-512.png   staff PWA (white tile, full-colour mark;
      maskable / apple-touch full bleed, mark inside the central 80 % safe zone)
  ui/ui/images/brand/favicon.svg        white rounded tile + the micro mark (vector; legible on light and dark tabs)
  ui/ui/images/favicon.ico, favicon.ico 16/32/48 (the print pages and the implicit /favicon.ico request)
  system/uploads/favicon.default.png, login-logo.default.png   defaults of the operator login pages (shown only when the
      operator uploaded nothing: the product, as Brand::company falls back to the product name)
  install/img/netcore-logo.png, install/img/netcore-favicon.png   installer (a product location); the upstream
      install/img/logo.png and favicon.png stay unchanged for the upstream documentation that shows them
Same inputs + same toolchain (rsvg-convert 2.58, Pillow 10.2) -> the same files; the run prints versions and SHA-256.
"""
import hashlib
import io
import os
import subprocess

from PIL import Image, ImageDraw, __version__ as PIL_VERSION

B = 'ui/ui/images/brand'
MARK = f'{B}/netcore-mark.svg'
MICRO = f'{B}/netcore-mark-micro.svg'
WORD = f'{B}/netcore-wordmark.svg'
WHITE = (255, 255, 255, 255)
SS = 4
RADIUS = 0.22


def svg(path: str, w: int, h: int | None = None) -> Image.Image:
    args = ['rsvg-convert', '-w', str(w)] + (['-h', str(h)] if h else []) + [path]
    return Image.open(io.BytesIO(subprocess.run(args, check=True, capture_output=True).stdout)).convert('RGBA')


def tile(size: int, mark_path: str, frac: float, full_bleed: bool) -> Image.Image:
    big = size * SS
    img = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if full_bleed:
        d.rectangle([0, 0, big - 1, big - 1], fill=WHITE)
    else:
        d.rounded_rectangle([0, 0, big - 1, big - 1], radius=int(big * RADIUS), fill=WHITE)
    m = svg(mark_path, int(big * frac))
    img.alpha_composite(m, ((big - m.width) // 2, (big - m.height) // 2))
    return img.resize((size, size), Image.LANCZOS)


def save(img: Image.Image, path: str, **kw) -> None:
    os.makedirs(os.path.dirname(path) or '.', exist_ok=True)
    img.save(path, **kw)
    print(f'{path} {img.width}x{img.height} sha256={hashlib.sha256(open(path, "rb").read()).hexdigest()}')


def main() -> None:
    ver = subprocess.run(['rsvg-convert', '--version'], check=True, capture_output=True, text=True).stdout.strip()
    print(f'{ver}; Pillow {PIL_VERSION}')
    # staff PWA (purpose any: rounded tile; maskable / apple-touch: full bleed, the platform applies its own mask)
    save(tile(180, MARK, 0.78, True), 'ui/ui/images/pwa/icon-180.png', format='PNG')
    save(tile(192, MARK, 0.86, False), 'ui/ui/images/pwa/icon-192.png', format='PNG')
    save(tile(512, MARK, 0.86, False), 'ui/ui/images/pwa/icon-512.png', format='PNG')
    save(tile(512, MARK, 0.66, True), 'ui/ui/images/pwa/icon-maskable-512.png', format='PNG')
    # favicon: vector (white rounded tile + the micro mark) and ICO 16/32/48 (micro mark: legible at 16 px)
    micro = open(MICRO, encoding='utf-8').read()
    inner = micro[micro.index('>') + 1:micro.rindex('</svg>')]
    fav = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 224 224"><rect width="224" height="224" rx="48" fill="#ffffff"/>'
           f'<g transform="translate(14 14) scale(0.875)">{inner}</g></svg>\n')
    with open(f'{B}/favicon.svg', 'w', encoding='utf-8') as f:
        f.write(fav)
    print(f'{B}/favicon.svg sha256={hashlib.sha256(fav.encode()).hexdigest()}')
    ico = tile(48, MICRO, 0.92, False)
    for p in ('ui/ui/images/favicon.ico', 'favicon.ico'):
        save(ico, p, format='ICO', sizes=[(16, 16), (32, 32), (48, 48)])
    save(tile(32, MICRO, 0.92, False), 'system/uploads/favicon.default.png', format='PNG')
    save(tile(69, MARK, 0.86, False), 'install/img/netcore-favicon.png', format='PNG')
    # wordmark rasters (transparent background, the light artwork): operator login default and the installer header
    save(svg(WORD, 300, None), 'system/uploads/login-logo.default.png', format='PNG')
    save(svg(WORD, 457, None), 'install/img/netcore-logo.png', format='PNG')


if __name__ == '__main__':
    main()
