<?php
/**
 * Development tool (CLI only): regenerates system/reseller/Migration/variants.php — the
 * authoritative core-schema contract of every explicitly verified baseline variant on every
 * supported engine family.
 *
 * It builds V1/V2/V3 (tests/Support/FixtureBuilder) in disposable databases on each given server,
 * canonicalises the core tables WP1 depends on and writes the registry. The output is a reviewed
 * source change; the runner never accepts variants at runtime.
 *
 * Usage (inside the dev/test PHP 8.2 container, see dev/test/run-tests.sh):
 *   php dev/tools/build-variant-registry.php --hosts=mariadb,mysql --password-env=WP1_DB_ROOT_PASSWORD [--check]
 *   --check  compare with the committed registry instead of writing it (exit 1 on difference)
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$root = dirname(__DIR__, 2);
require_once $root . '/system/reseller/Migration/Outcome.php';
require_once $root . '/system/reseller/Migration/Db.php';
require_once $root . '/system/reseller/Migration/SchemaInspector.php';
require_once $root . '/system/reseller/Migration/VariantRegistry.php';
require_once $root . '/tests/Support/FixtureBuilder.php';

use Reseller\Migration\Db;
use Reseller\Migration\SchemaInspector;
use Reseller\Migration\VariantRegistry;
use Reseller\Tests\Support\FixtureBuilder;

$opts = getopt('', ['hosts:', 'password-env:', 'check']);
$hosts = explode(',', (string) ($opts['hosts'] ?? ''));
$password = getenv((string) ($opts['password-env'] ?? ''));
if ($hosts === [''] || $password === false) {
    fwrite(STDERR, "usage: --hosts=h1,h2 --password-env=VAR [--check]\n");
    exit(5);
}

function export_value(mixed $v, int $indent = 0): string
{
    $pad = str_repeat('    ', $indent);
    if (is_array($v)) {
        if ($v === []) {
            return '[]';
        }
        $list = array_is_list($v);
        $lines = [];
        foreach ($v as $k => $item) {
            $lines[] = $pad . '    ' . ($list ? '' : var_export($k, true) . ' => ') . export_value($item, $indent + 1) . ',';
        }
        return "[\n" . implode("\n", $lines) . "\n" . $pad . ']';
    }
    return var_export($v, true);
}

$builder = new FixtureBuilder($root);
$registry = [];
$provenance = [];
foreach ($hosts as $host) {
    $admin = FixtureBuilder::connect($host, (string) $password);
    foreach (FixtureBuilder::ALL as $variant) {
        $dbName = 'nuxr_variant_' . strtolower(substr($variant, 0, 2)) . '_' . bin2hex(random_bytes(4));
        $admin->exec("CREATE DATABASE `{$dbName}` CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci");
        try {
            $stats = $builder->build(FixtureBuilder::connect($host, (string) $password, $dbName), $variant);
            $db = new Db($host, $dbName, 'root', (string) $password);
            $inspector = new SchemaInspector($db);
            $core = [];
            foreach (VariantRegistry::CORE_TABLES as $t) {
                $core[$t] = SchemaInspector::normalise($inspector->table($t));
            }
            $registry[$db->engineFamily][$variant] = $core;
            $provenance[] = sprintf('%s %s on %s: %d install statements, legacy updates ok=%d failed(ignored by update.php)=%d, core fingerprint %s',
                $db->engineFamily, $variant, $db->serverVersion, $stats['statements'], $stats['update_ok'], $stats['update_failed'], SchemaInspector::fingerprint($core));
        } finally {
            $admin->exec("DROP DATABASE `{$dbName}`");
        }
    }
}
ksort($registry);

$inputs = [];
foreach (['install/phpnuxbill.sql', 'system/updates.json', 'tests/fixtures/schema/phpnuxbill.2023-08-09.sql'] as $f) {
    $inputs[] = hash_file('sha256', $root . '/' . $f) . '  ' . $f;
}

$php = "<?php\n"
    . "// CLI-only data file: authoritative core-schema contract (owner decisions C13 / C27 / Q3).\n"
    . "if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }\n\n"
    . "/*\n * GENERATED by dev/tools/build-variant-registry.php from the WP0-verified fixtures.\n"
    . " * Do not edit by hand. Adding a variant requires a reviewed source change and tests.\n *\n"
    . " * Inputs:\n" . implode("\n", array_map(static fn(string $l): string => " *   {$l}", $inputs)) . "\n *\n"
    . " * Built:\n" . implode("\n", array_map(static fn(string $l): string => " *   {$l}", $provenance)) . "\n */\n\n"
    . 'return ' . export_value($registry) . ";\n";

$target = $root . '/system/reseller/Migration/variants.php';
if (isset($opts['check'])) {
    $current = is_file($target) ? (static fn(string $f) => require $f)($target) : null;
    if ($current !== $registry) {
        fwrite(STDERR, "variant registry differs from freshly built fixtures\n");
        exit(1);
    }
    echo "variant registry matches freshly built fixtures\n";
    foreach ($provenance as $p) {
        echo "  {$p}\n";
    }
    exit(0);
}
file_put_contents($target, $php);
echo "wrote {$target}\n";
foreach ($provenance as $p) {
    echo "  {$p}\n";
}
