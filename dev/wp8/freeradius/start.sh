#!/bin/sh
# WP8 lab FreeRADIUS (development/test only): the project configuration from install/freeradius with the NAS clients
# loaded from the PHPNuxBill `nas` table (read_clients = yes, client_table = nas) - the production arrangement - and
# only a static localhost client in clients.conf. Message-Authenticator enforcement comes from the project virtual
# server itself (install/freeradius/sites-available/phpnuxbill, owner decision OD-W8-13); nothing here relaxes or
# tightens it. Runs in debug mode (-X) because the lab evidence needs the request handling; the container log is
# ephemeral and evidence excerpts are redacted (dev/wp8/redact.py).
set -eu
R=/etc/freeradius
cp /nuxr/install/dictionary.phpnuxbill "$R/dictionary.phpnuxbill"
grep -q 'dictionary.phpnuxbill' "$R/dictionary" || echo '$INCLUDE dictionary.phpnuxbill' >> "$R/dictionary"
cp /nuxr/install/mods-available/nuxr_counters "$R/mods-enabled/nuxr_counters"
sed -e 's/read_clients = no/read_clients = yes/' /nuxr/test/sql > "$R/mods-enabled/sql"
grep -q 'read_clients = yes' "$R/mods-enabled/sql"
rm -f "$R"/sites-enabled/* "$R/mods-enabled/eap"
cp /nuxr/install/sites-available/phpnuxbill "$R/sites-enabled/phpnuxbill"
# WP8 A2-R FAULT INJECTION (lab only, off unless dev/wp8/a2r_gate.py fault on created BOTH files inside this disposable
# container): a copy of the PROJECT site generated by the gate tool with SQL delays inserted at two named points, active
# only for requests carrying NAS-Identifier "nuxr-a2r-fault-*" (gate cases: creator failure after an accepted attacher,
# database connection lost before the claim). Never shipped; install/freeradius is unchanged. Removed by fault off and
# by lab.sh down (container recreated).
if [ -f "$R/wp8-a2r-fault" ] && [ -f "$R/wp8-a2r-fault-site" ]; then
	cp "$R/wp8-a2r-fault-site" "$R/sites-enabled/phpnuxbill"
	echo "[wp8] A2-R FAULT-INJECTION site: $(sha256sum "$R/sites-enabled/phpnuxbill" | cut -c1-16)"
fi
# WP8 H-1 FEASIBILITY (lab only, off unless dev/wp8/h1_gate.py site h1b created BOTH files inside this disposable
# container): a copy of the PROJECT site with ONE experimental Hotspot post-auth block (H1-B: reply User-Name = the
# canonical radcheck.username). Not the project policy; install/freeradius is unchanged. Removed by "h1_gate.py site
# project" and by lab.sh down (container recreated).
if [ -f "$R/wp8-h1-site-on" ] && [ -f "$R/wp8-h1-site" ]; then
	cp "$R/wp8-h1-site" "$R/sites-enabled/phpnuxbill"
	echo "[wp8] H-1 FEASIBILITY site (H1-B): $(sha256sum "$R/sites-enabled/phpnuxbill" | cut -c1-16)"
fi
printf 'client localhost {\n\tipaddr = 127.0.0.1\n\tsecret = $ENV{NUXR_RADIUS_SECRET}\n\trequire_message_authenticator = yes\n}\n' > "$R/clients.conf"
# OD-W8-16 Option F checkrad GATE (lab only, off unless dev/wp8/checkrad_gate.py created the marker inside this
# disposable container): Simultaneous-Use verification by the STOCK FreeRADIUS 3.2.8 checkrad (nas.type
# mikrotik_snmp, community from naspasswd), with delete_stale_sessions = no so a stale radacct row is never zapped.
# The image's checkrad was built without net-snmp, so autoconf left its two program paths empty ($snmpget = "",
# $snmpwalk = ""); the lab copy sets exactly those two build-time paths and nothing else. A trace wrapper records
# argv (no community) and the exit code of every checkrad run for the evidence; it never changes the result.
sed -i -e 's|^checkrad = .*|checkrad = ${sbindir}/checkrad|' "$R/radiusd.conf"     # stock unless a gate below says otherwise
if [ -f "$R/wp8-checkrad-gate" ]; then
	command -v snmpwalk >/dev/null || echo "[wp8] checkrad gate: snmpwalk NOT installed"
	grep -q 'delete_stale_sessions = no' "$R/mods-enabled/sql"
	rm -f "$R/wp8-checkrad"      # may be the Option G symlink to /usr/sbin/checkrad: never write through it
	sed -e 's|^\$snmpget\t= "";|$snmpget\t= "/usr/bin/snmpget";|' -e 's|^\$snmpwalk\t= "";|$snmpwalk\t= "/usr/bin/snmpwalk";|' /usr/sbin/checkrad > "$R/wp8-checkrad"
	install -m 0755 /nuxr/wp8/checkrad-trace.sh "$R/wp8-checkrad-trace"
	chmod 0755 "$R/wp8-checkrad"
	sed -i -e "s|^checkrad = .*|checkrad = $R/wp8-checkrad-trace|" "$R/radiusd.conf"
	echo "[wp8] checkrad gate: $(grep -E '^checkrad = ' "$R/radiusd.conf") $(grep -E 'delete_stale_sessions' "$R/mods-enabled/sql" | tr -s '\t ' ' ') checkrad-diff-lines=$(diff /usr/sbin/checkrad "$R/wp8-checkrad" | grep -c '^[<>]') naspasswd=$(stat -c '%a %U' "$R/naspasswd" 2>/dev/null || echo missing)"
fi
# WP8 A1 - PPPoE session guard (OD-W8-16 Option G), PERMANENT: the program and the named exec module come from
# install/freeradius exactly as install/freeradius/README.md describes, and the post-auth policy is part of the
# project virtual server copied above (no lab include, so it can never run twice). The guard credential file is the
# persistent lab file $NUXR_WP8_STATE/radius-secrets/nas_snmp (rendered by dev/wp8/option_g_gate.py, mounted read-only
# at /nuxr/secrets), installed on every start as $R/nuxr/nas_snmp (0600 freerad); without it every PPPoE login that
# meets an open radacct row is rejected (fail closed). The dev/wp8/freeradius/option-g/ copy is the gate reference
# only and is not used here.
mkdir -p "$R/nuxr"; chmod 0755 "$R/nuxr"
install -m 0755 /nuxr/install/bin/nuxr_pppoe_session_guard "$R/nuxr/nuxr_pppoe_session_guard"
cp /nuxr/install/mods-available/nuxr_pppoe_session_guard "$R/mods-enabled/nuxr_pppoe_session_guard"
# WP8 H-2B - Hotspot slot verifier (same credential file $R/nuxr/nas_snmp), installed as install/freeradius/README.md says
install -m 0755 /nuxr/install/bin/nuxr_hotspot_slot_verifier "$R/nuxr/nuxr_hotspot_slot_verifier"
cp /nuxr/install/mods-available/nuxr_hotspot_slot_verifier "$R/mods-enabled/nuxr_hotspot_slot_verifier"
if [ -f /nuxr/secrets/nas_snmp ]; then
	install -m 0600 -o freerad -g freerad /nuxr/secrets/nas_snmp "$R/nuxr/nas_snmp"
else
	rm -f "$R/nuxr/nas_snmp"
fi
test -x "$R/nuxr/nuxr_pppoe_session_guard"
test -x /usr/bin/snmpget
test -x /usr/bin/snmpbulkwalk
test "$(grep -c '^[[:space:]]*nuxr_pppoe_session_guard {' "$R/sites-enabled/phpnuxbill")" = 1
test -x "$R/nuxr/nuxr_hotspot_slot_verifier"
test "$(grep -c '^[[:space:]]*nuxr_hotspot_slot_verifier {' "$R/sites-enabled/phpnuxbill")" = 1
if grep -q 'option-g' "$R/sites-enabled/phpnuxbill"; then echo "[wp8] lab option-g policy referenced by the site"; exit 1; fi
grep -q 'delete_stale_sessions = no' "$R/mods-enabled/sql"
# Gate tooling marker (dev/wp8/option_g_gate.py on): the stock checkrad AS SHIPPED (/usr/sbin/checkrad, unmodified,
# reached through a symlink) behind the trace wrapper, for the evidence. Unless the checkrad gate marker above is also
# present (lab-only "functional stock checkrad" variant), which already installed the lab copy.
if [ -f "$R/wp8-option-g" ] && [ ! -f "$R/wp8-checkrad-gate" ]; then
	ln -sf /usr/sbin/checkrad "$R/wp8-checkrad"
	install -m 0755 /nuxr/wp8/checkrad-trace.sh "$R/wp8-checkrad-trace"
	sed -i -e "s|^checkrad = .*|checkrad = $R/wp8-checkrad-trace|" "$R/radiusd.conf"
fi
echo "[wp8] session guard: guard=$(sha256sum "$R/nuxr/nuxr_pppoe_session_guard" | cut -c1-16) $(grep -E 'delete_stale_sessions' "$R/mods-enabled/sql" | tr -s '\t ' ' ') $(grep -E '^checkrad = ' "$R/radiusd.conf") stock-checkrad=$(readlink "$R/wp8-checkrad" 2>/dev/null || echo stock) creds=$(stat -c '%a %U' "$R/nuxr/nas_snmp" 2>/dev/null || echo missing) gate_marker=$(test -f "$R/wp8-option-g" && echo 1 || echo 0)"
echo "[wp8] TZ=${TZ:-unset} sql: $(grep -E 'read_clients|client_table' "$R/mods-enabled/sql" | tr -s '\t ' ' ' | tr '\n' ' ')"
echo "[wp8] global: $(sed -n '/^security {/,/^}/p' "$R/radiusd.conf" | grep -E '^\s*require_message_authenticator' | tr -s '\t ' ' ')"
# WP8 A2-R AV-2 (lab only, marker set by dev/wp8/a2r_gate.py pool N): the SQL pool max of the lab module (8, from
# dev/test/freeradius/sql) replaced by N for the pool-sizing measurement; removed by "a2r_gate.py pool off".
if [ -f "$R/wp8-a2r-pool" ]; then
	N=$(tr -cd '0-9' < "$R/wp8-a2r-pool")
	sed -i -E "s/^([[:space:]]*max = )[0-9]+$/\1${N}/" "$R/mods-enabled/sql"
	echo "[wp8] A2-R AV-2: sql pool $(grep -E '^[[:space:]]*max = ' "$R/mods-enabled/sql" | tr -s '\t ' ' ')"
fi
# WP8 A2-R GATE (lab only, marker set by dev/wp8/a2r_gate.py threaded on): `freeradius -X` implies -s (ONE
# thread, requests strictly sequential), so concurrent requests can never race inside FreeRADIUS; the gate's
# concurrency cases run with the production thread pool instead (same debug output, request-prefixed lines).
if [ -f "$R/wp8-a2r-threaded" ]; then
	echo "[wp8] A2-R gate: threaded (freeradius -fxx -l stdout)"
	exec freeradius -fxx -l stdout
fi
exec freeradius -X
