AR = '٠١٢٣٤٥٦٧٨٩'
used = set()


def ar(n):
    return ''.join(AR[int(c)] for c in str(n))


def F(name, cap, alt=None):
    assert name in DIMS, name
    used.add(name)
    w, h = DIMS[name]
    return (f'<figure><img class="shot" src="img/{name}.webp" width="{w}" height="{h}" alt="{alt or name}">'
            f'<figcaption>{cap}</figcaption></figure>')


def PAIR(*figs):
    return '<div class="pair">' + ''.join(figs) + '</div>'


def PHONES(items, cls='phones'):
    return f'<div class="{cls}">' + ''.join(F(n, c) for n, c in items) + '</div>'


def P(*ps):
    return '<div class="text read">' + ''.join(f'<p>{p}</p>' for p in ps) + '</div>'


def H3(t):
    return f'<div class="read"><h3>{t}</h3></div>'


def STEPS(items, intro=None):
    s = '<div class="text read">'
    if intro:
        s += f'<p>{intro}</p>'
    s += '<ol class="steps">' + ''.join(f'<li><span>{i}</span></li>' for i in items) + '</ol></div>'
    return s


def NOTE(t, warn=False):
    return f'<div class="note read{" warn" if warn else ""}">{t}</div>'


def TICKS(items):
    return '<div class="read"><ul class="ticks">' + ''.join(f'<li>{i}</li>' for i in items) + '</ul></div>'


CH = []


def chapter(cid, title, lede, *body):
    CH.append((cid, title, lede, ''.join(body)))


