#!/usr/bin/env python3
"""Release-artifact notices bundle (D10): collects the licence texts that ship with the Composer packages and the vendored libraries.

  dev/wp10/notices_bundle.py OUT_FILE

Writes one text file (package, licence from composer.lock, licence text found in the package) and prints what is MISSING. It invents no copyright
holder and no licence text: a package without a licence file is listed as missing and has to be completed from its upstream by the maintainers /
counsel (owner-review/WP10/LEGAL_REVIEW_PACKAGE.md section 4). Exit 1 when something is missing (the release-artifact checklist is then open).
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def main(out):
    lock = json.load(open(os.path.join(ROOT, 'system', 'composer.lock')))
    missing = []
    parts = ['THIRD-PARTY NOTICES (generated by dev/wp10/notices_bundle.py; this is a collection of files found in the packages, not legal advice)\n']
    for p in lock['packages']:
        d = os.path.join(ROOT, 'system', 'vendor', p['name'])
        files = [f for f in sorted(glob.glob(os.path.join(d, '*'))) if re.match(r'^(licen[sc]e|copying|notice)', os.path.basename(f), re.I)]
        parts.append('=' * 78 + f"\n{p['name']} {p['version']}  licence (composer metadata): {', '.join(p.get('license') or ['?'])}\n" + '=' * 78 + '\n')
        if not files:
            missing.append(p['name'])
            parts.append('[MISSING] this package ships no licence file; obtain it from the upstream project before distribution\n')
            continue
        for f in files:
            parts.append(f'--- {os.path.relpath(f, ROOT)}\n' + open(f, errors='replace').read() + '\n')
    for extra in ('LICENSE',):
        parts.append('=' * 78 + f'\n{extra} (this application)\n' + '=' * 78 + '\n' + open(os.path.join(ROOT, extra), errors='replace').read() + '\n')
    for f in sorted(glob.glob(os.path.join(ROOT, 'ui', 'ui', 'summernote', '*LICENSE*'))):
        parts.append(f'--- {os.path.relpath(f, ROOT)}\n' + open(f, errors='replace').read() + '\n')
    open(out, 'w').write('\n'.join(parts))
    print(f'wrote {out} ({os.path.getsize(out)} bytes)')
    if missing:
        print('MISSING licence files: ' + ', '.join(missing))
        sys.exit(1)


if __name__ == '__main__':
    main(sys.argv[1])
