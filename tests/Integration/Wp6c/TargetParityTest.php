<?php
namespace Reseller\Tests\Integration\Wp6c;

// CLI-only test: must never run through the web server.
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }

use Reseller\Tests\Support\Wp2HttpTestCase;

/**
 * WP6C fix round 1 (owner amendment A, target level): a row action or identity link is rendered only when the specific
 * target passes the accepted target policy, not merely the route rule. Staff rows: view = the settings controller's
 * staff-visibility rule, edit / delete = StaffService::canTarget (+ the explicit V1 "Agents are never deleted" rule of
 * StaffService::delete). A parent / generator identity the actor may not view is plain text. A voucher's customer is
 * linked only when DataScope finds that customer for the actor. Backend authorization is unchanged and authoritative.
 */
final class TargetParityTest extends Wp2HttpTestCase
{
    private static int $saVoucher;
    private static int $foreignCustomerVoucher;

    public static function setUpBeforeClass(): void
    {
        parent::setUpBeforeClass();
        $s = static::$seed;
        // a voucher Admin can list (G) but whose generator (a SuperAdmin) Admin may not view
        self::$saVoucher = static::$db->insertRow('tbl_voucher', [
            'type' => 'Hotspot', 'routers' => 'wp2_router', 'id_plan' => $s->planId, 'code' => 'WP6CSA' . bin2hex(random_bytes(3)),
            'user' => '0', 'status' => '0', 'generated_by' => $s->staff['sa'],
        ]);
        // a voucher in Agent A's subtree (generated by B) redeemed by a customer outside A's customer scope (C's)
        self::$foreignCustomerVoucher = static::$db->insertRow('tbl_voucher', [
            'type' => 'Hotspot', 'routers' => 'wp2_router', 'id_plan' => $s->planId, 'code' => 'WP6CXC' . bin2hex(random_bytes(3)),
            'user' => 'cC1', 'status' => '1', 'generated_by' => $s->staff['B'],
        ]);
    }

    private static function hasLink(string $html, string $route, int|string $id): bool
    {
        return (bool) preg_match('#href="[^"]*\?_route=' . preg_quote($route, '#') . '/?' . preg_quote((string) $id, '#') . '"#', $html);
    }

    public function testAdminIsNotOfferedDeleteForASalesAccount(): void
    {
        $s = static::$seed;
        $html = $this->staff('ad')->get('settings/users')->body;
        $this->assertTrue(self::hasLink($html, 'settings/users-view/', $s->staff['A1']), 'the Sales row itself is listed and viewable');
        $this->assertFalse(self::hasLink($html, 'settings/users-delete/', $s->staff['A1']), 'Admin may permanently delete Report accounts only');
        $this->assertFalse(self::hasLink($html, 'settings/users-delete/', $s->staff['A']), 'Agents are never deleted (V1)');
        // the accepted writer still refuses it (unchanged backend)
        $r = $this->staff('ad')->postWithToken('settings/users-delete/' . $s->staff['A1'], []);
        $this->assertSame(302, $r->status);
        $this->assertSame(1, (int) static::$db->value('SELECT COUNT(*) FROM tbl_users WHERE id = ?', [$s->staff['A1']]), 'Sales account not deleted');
    }

    public function testAdminKeepsDeleteForAReportAccountAndUsableLinks(): void
    {
        $s = static::$seed;
        $html = $this->staff('ad')->get('settings/users')->body;
        $this->assertTrue(self::hasLink($html, 'settings/users-delete/', $s->staff['rp']), 'StaffService permits Admin to delete a Report account');
        foreach (['A', 'A1', 'rp'] as $u) {
            $this->assertTrue(self::hasLink($html, 'settings/users-edit/', $s->staff[$u]), "Admin keeps Edit for {$u}");
        }
        // every rendered staff view / edit link opens (no "Account Not Found", no 403)
        preg_match_all('#href="[^"]*\?_route=(settings/users-(?:view|edit)/\d+)"#', $html, $m);
        $this->assertNotEmpty($m[1]);
        foreach (array_unique($m[1]) as $route) {
            $r = $this->staff('ad')->get($route);
            $this->assertSame(200, $r->status, $route);
            $this->assertStringNotContainsString('Account Not Found', $r->body, $route);
        }
    }

    public function testSalesGetsNoLinkToItsParentAgent(): void
    {
        $s = static::$seed;
        $c = $this->staff('A1');
        $html = $c->get('settings/users')->body;
        $this->assertTrue(self::hasLink($html, 'settings/users-view/', $s->staff['A1']), 'Sales views itself');
        $this->assertFalse(self::hasLink($html, 'settings/users-view/', $s->staff['A']), 'the parent Agent is not a target Sales may read');
        $this->assertFalse(self::hasLink($html, 'settings/users-delete/', $s->staff['A1']), 'never delete self');
        $this->assertSame(302, $c->get('settings/users-view/' . $s->staff['A'])->status, 'the backend refuses that target (unchanged: redirect with "Account Not Found")');
        $c->get('dashboard'); // consume the flash
        // the Agent keeps working links to its own subtree
        $agent = $this->staff('A')->get('settings/users')->body;
        $this->assertTrue(self::hasLink($agent, 'settings/users-view/', $s->staff['A1']), 'Agent views its Sales');
        $this->assertTrue(self::hasLink($agent, 'settings/users-edit/', $s->staff['A1']), 'Agent edits its Sales');
    }

    public function testVoucherGeneratorLinksOnlyToViewableStaff(): void
    {
        $s = static::$seed;
        $ad = $this->staff('ad');
        $html = $ad->get('plan/voucher')->body;
        $this->assertStringContainsString('WP6CSA', $html, 'Admin lists the SuperAdmin-generated voucher');
        $this->assertFalse(self::hasLink($html, 'settings/users-view/', $s->staff['sa']), 'generator Admin may not view: plain text');
        $this->assertSame(302, $ad->get('settings/users-view/' . $s->staff['sa'])->status, 'fixture is meaningful: Admin may not view a SuperAdmin');
    }

    public function testVoucherCustomerLinksOnlyToCustomersInScope(): void
    {
        // Agent A: a voucher of its subtree redeemed by a customer outside its scope -> the customer is not linked
        $a = $this->staff('A');
        $va = $a->get('plan/voucher')->body;
        $this->assertStringContainsString('WP6CXC', $va, 'A lists the subtree voucher');
        $this->assertFalse(self::hasLink($va, 'customers/viewu/', 'cC1'), 'out-of-scope customer is plain text');
        $denied = $a->get('customers/viewu/cC1');
        $this->assertTrue($denied->status !== 200 || !str_contains($denied->body, 'cC1'), 'the backend does not open that customer for A (fixture is meaningful)');
        // in-scope customer links on the same page still open
        preg_match_all('#href="[^"]*\?_route=(customers/viewu/[^"&]+)"#', $va, $m);
        foreach (array_unique($m[1]) as $route) {
            $r = $a->get($route);
            $this->assertSame(200, $r->status, $route);
            $this->assertStringNotContainsString('nuxr-state-page', $r->body, $route);
        }
    }
}
